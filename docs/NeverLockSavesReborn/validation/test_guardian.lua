local function last(g) local r=g:latest();return r[#r] end
local function evidenceUnknown(g)
  for _,r in ipairs(g:report().records) do
    eq(r.write_status,'Unknown','write evidence cannot be invented')
    eq(r.reload_status,'Unknown','reload evidence cannot be invented')
  end
end
